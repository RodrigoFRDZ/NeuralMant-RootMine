def guardar(usuario, tipo, titulo, objetivo='', finalidad='', padre_id=None, **campos):
    if not autorizado(usuario): raise PermissionError('Acceso denegado')
    permitidos = {'estado','responsable','fecha_limite','indicador','linea_base','meta','valor_actual','evidencia','origen','avance','ultima_gestion','presentada'}
    datos = {'propietario':OWNER,'tipo':tipo,'titulo':titulo,'objetivo':objetivo,'finalidad':finalidad,'padre_id':padre_id,'creado':datetime.now().isoformat(timespec='seconds'),'actualizado':datetime.now().isoformat(timespec='seconds')}
    datos.update({k:str(v) for k,v in campos.items() if k in permitidos})
    cols=', '.join(datos)
    with engine.begin() as con:
        if padre_id is not None:
            ok=con.execute(text('SELECT 1 FROM mi_gestion_item WHERE id=:id AND propietario=:p'),{'id':padre_id,'p':OWNER}).first()
            if not ok: raise ValueError('Objetivo no encontrado')
        if tipo == 'subtarea':
            padre=con.execute(text('SELECT tipo, padre_id FROM mi_gestion_item WHERE id=:id AND propietario=:p'),{'id':padre_id,'p':OWNER}).mappings().first()
            if not padre or padre['tipo'] not in ('tarea','compromiso'):
                raise ValueError('Una subtarea debe pertenecer a una tarea principal')
        con.execute(text(f'INSERT INTO mi_gestion_item ({cols}) VALUES ({", ".join(":"+k for k in datos)})'),datos)
        if tipo == 'subtarea':
            _recalcular_padre(con,padre_id)


def _recalcular_padre(con, padre_id):
    padre=con.execute(text('SELECT id, estado, avance FROM mi_gestion_item WHERE id=:i AND propietario=:p AND tipo IN (\'tarea\',\'compromiso\')'),{'i':padre_id,'p':OWNER}).mappings().first()
    if not padre: raise ValueError('Tarea principal no encontrada')
    hijos=con.execute(text("SELECT estado, avance FROM mi_gestion_item WHERE padre_id=:i AND propietario=:p AND tipo='subtarea'"),{'i':padre_id,'p':OWNER}).mappings().all()
    activos=[h for h in hijos if h['estado'] not in ('Cancelada','Descartada')]
    if not activos:
        if hijos:  # Todas canceladas: no cerrar; dejar la tarea pendiente de revisión manual.
            con.execute(text("UPDATE mi_gestion_item SET estado='Pendiente', avance=0, actualizado=:t WHERE id=:i AND propietario=:p"),{'t':datetime.now().isoformat(timespec='seconds'),'i':padre_id,'p':OWNER})
            _historial(con,padre_id,'Todas las subtareas canceladas: tarea principal pendiente de revisión')
        return  # Sin ninguna subtarea: conserva gestión manual.
    valores=[100 if h['estado']=='Finalizada' else 0 if h['estado']=='Pendiente' else int(h['avance'] or 0) for h in activos]
    avance=round(sum(valores)/len(valores),2)
    estado='Finalizada' if all(h['estado']=='Finalizada' for h in activos) else 'Pendiente' if all(v==0 for v in valores) else 'En ejecución'
    if estado!=padre['estado'] or abs(float(padre['avance'] or 0)-avance)>0.001:
        ahora=datetime.now().isoformat(timespec='seconds')
        con.execute(text('UPDATE mi_gestion_item SET estado=:e,avance=:a,actualizado=:t WHERE id=:i AND propietario=:p'),{'e':estado,'a':avance,'t':ahora,'i':padre_id,'p':OWNER})
        _historial(con,padre_id,f'Avance consolidado: {avance}% · {estado}')


