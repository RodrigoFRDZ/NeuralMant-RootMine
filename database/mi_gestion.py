def actualizar(usuario, id, **campos):
    if not autorizado(usuario): raise PermissionError('Acceso denegado')
    permitidos={'estado','finalidad','responsable','fecha_limite','evidencia','valor_actual','meta','linea_base','indicador','objetivo','titulo','avance','ultima_gestion','presentada'}
    with engine.begin() as con:
        actual=con.execute(text('SELECT * FROM mi_gestion_item WHERE id=:i AND propietario=:p'),{'i':id,'p':OWNER}).mappings().first()
        if not actual: raise ValueError('Registro no encontrado')
        if actual['tipo'] in ('tarea','compromiso') and any(k in campos for k in ('avance','estado')):
            hijos=con.execute(text("SELECT COUNT(*) FROM mi_gestion_item WHERE padre_id=:i AND propietario=:p AND tipo='subtarea' AND estado NOT IN ('Cancelada','Descartada')"),{'i':id,'p':OWNER}).scalar()
            if hijos: raise ValueError('El estado y avance de esta tarea se calculan automáticamente desde sus subtareas')
        if 'estado' in campos and actual['tipo']=='subtarea':
            if campos['estado'] not in ('Pendiente','En ejecución','Finalizada','Cancelada'):
                raise ValueError('Estado de subtarea inválido')
            if campos['estado']=='Finalizada': campos['avance']=100
            elif campos['estado'] in ('Pendiente','Cancelada'): campos['avance']=0
            elif 'avance' not in campos: campos['avance']=int(actual['avance'] or 0) if 1<=int(actual['avance'] or 0)<=99 else 10
        if 'avance' in campos:
            campos['avance']=max(0,min(100,float(campos['avance'])))
            if actual['tipo']=='subtarea':
                estado=campos.get('estado',actual['estado'])
                if estado=='En ejecución' and not 1<=campos['avance']<=99: raise ValueError('En ejecución requiere avance de 1 a 99%')
                if estado=='Finalizada' and campos['avance']!=100: raise ValueError('Finalizada requiere 100%')
                if estado in ('Pendiente','Cancelada') and campos['avance']!=0: raise ValueError('Pendiente o cancelada requiere 0%')
        datos={k:str(v) for k,v in campos.items() if k in permitidos}
        if not datos:return
        datos.update({'id':id,'p':OWNER,'actualizado':datetime.now().isoformat(timespec='seconds')})
        con.execute(text('UPDATE mi_gestion_item SET '+', '.join(f'{k}=:{k}' for k in datos if k not in ('id','p'))+' WHERE id=:id AND propietario=:p'),datos)
        cambios=[f'{k}: {actual.get(k)} → {v}' for k,v in campos.items() if k in permitidos and str(actual.get(k))!=str(v)]
        if cambios:_historial(con,id,'; '.join(cambios))
        if actual['tipo']=='subtarea':_recalcular_padre(con,actual['padre_id'])


