"""Persistencia privada de Mi Gestión; acceso exclusivamente por correo autorizado."""
import json
from datetime import datetime
from sqlalchemy import text
from database.conexion import engine

OWNER = 'rfernandezc@agrosuper.com'

def autorizado(usuario):
    return str((usuario or {}).get('correo','')).strip().lower() == OWNER

def preparar():
    with engine.begin() as con:
        con.execute(text('''CREATE TABLE IF NOT EXISTS mi_gestion_item (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            propietario VARCHAR(180) NOT NULL,
            tipo VARCHAR(35) NOT NULL,
            titulo TEXT NOT NULL,
            objetivo TEXT NOT NULL DEFAULT '',
            finalidad TEXT NOT NULL DEFAULT '',
            estado VARCHAR(40) NOT NULL DEFAULT 'Pendiente',
            responsable TEXT NOT NULL DEFAULT '',
            fecha_limite VARCHAR(20) NOT NULL DEFAULT '',
            indicador VARCHAR(100) NOT NULL DEFAULT '',
            linea_base VARCHAR(60) NOT NULL DEFAULT '',
            meta VARCHAR(60) NOT NULL DEFAULT '',
            valor_actual VARCHAR(60) NOT NULL DEFAULT '',
            evidencia TEXT NOT NULL DEFAULT '',
            origen TEXT NOT NULL DEFAULT '',
            padre_id INTEGER,
            creado VARCHAR(30) NOT NULL,
            actualizado VARCHAR(30) NOT NULL
        )'''.replace('INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY', 'INTEGER PRIMARY KEY AUTOINCREMENT') if engine.dialect.name == 'sqlite' else '''CREATE TABLE IF NOT EXISTS mi_gestion_item (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            propietario VARCHAR(180) NOT NULL, tipo VARCHAR(35) NOT NULL,
            titulo TEXT NOT NULL, objetivo TEXT NOT NULL DEFAULT '', finalidad TEXT NOT NULL DEFAULT '',
            estado VARCHAR(40) NOT NULL DEFAULT 'Pendiente', responsable TEXT NOT NULL DEFAULT '',
            fecha_limite VARCHAR(20) NOT NULL DEFAULT '', indicador VARCHAR(100) NOT NULL DEFAULT '',
            linea_base VARCHAR(60) NOT NULL DEFAULT '', meta VARCHAR(60) NOT NULL DEFAULT '',
            valor_actual VARCHAR(60) NOT NULL DEFAULT '', evidencia TEXT NOT NULL DEFAULT '',
            origen TEXT NOT NULL DEFAULT '', padre_id INTEGER, creado VARCHAR(30) NOT NULL,
            actualizado VARCHAR(30) NOT NULL)'''))
        # Migración no destructiva: conserva todas las tareas existentes.
        columnas = {r[1] if engine.dialect.name == 'sqlite' else r[0] for r in (con.execute(text('PRAGMA table_info(mi_gestion_item)')).fetchall() if engine.dialect.name == 'sqlite' else con.execute(text("SELECT column_name FROM information_schema.columns WHERE table_name='mi_gestion_item'")).fetchall())}
        if 'avance' not in columnas:
            con.execute(text('ALTER TABLE mi_gestion_item ADD COLUMN avance INTEGER NOT NULL DEFAULT 0'))
        if engine.dialect.name == 'postgresql':
            con.execute(text('ALTER TABLE mi_gestion_item ENABLE ROW LEVEL SECURITY'))

def listar(usuario):
    if not autorizado(usuario): raise PermissionError('Acceso denegado')
    with engine.connect() as con:
        return [dict(r) for r in con.execute(text('SELECT * FROM mi_gestion_item WHERE propietario=:p ORDER BY id DESC'), {'p':OWNER}).mappings()]

def guardar(usuario, tipo, titulo, objetivo='', finalidad='', padre_id=None, **campos):
    if not autorizado(usuario): raise PermissionError('Acceso denegado')
    permitidos = {'estado','responsable','fecha_limite','indicador','linea_base','meta','valor_actual','evidencia','origen','avance'}
    datos = {'propietario':OWNER,'tipo':tipo,'titulo':titulo,'objetivo':objetivo,'finalidad':finalidad,'padre_id':padre_id,'creado':datetime.now().isoformat(timespec='seconds'),'actualizado':datetime.now().isoformat(timespec='seconds')}
    datos.update({k:str(v) for k,v in campos.items() if k in permitidos})
    cols=', '.join(datos)
    with engine.begin() as con:
        if padre_id is not None:
            ok=con.execute(text('SELECT 1 FROM mi_gestion_item WHERE id=:id AND propietario=:p'),{'id':padre_id,'p':OWNER}).first()
            if not ok: raise ValueError('Objetivo no encontrado')
        con.execute(text(f'INSERT INTO mi_gestion_item ({cols}) VALUES ({", ".join(":"+k for k in datos)})'),datos)

def actualizar(usuario, id, **campos):
    if not autorizado(usuario): raise PermissionError('Acceso denegado')
    permitidos={'estado','finalidad','responsable','fecha_limite','evidencia','valor_actual','meta','linea_base','indicador','objetivo','titulo','avance'}
    if 'avance' in campos:
        campos['avance'] = max(0, min(100, int(campos['avance'])))
    datos={k:str(v) for k,v in campos.items() if k in permitidos}
    if not datos: return
    datos.update({'id':id,'p':OWNER,'actualizado':datetime.now().isoformat(timespec='seconds')})
    with engine.begin() as con:
        con.execute(text('UPDATE mi_gestion_item SET '+', '.join(f'{k}=:{k}' for k in datos if k not in ('id','p'))+' WHERE id=:id AND propietario=:p'),datos)
